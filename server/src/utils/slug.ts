export function slugify(value: string): string {
  return value
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80);
}

export async function buildUniqueSlug(
  value: string,
  exists: (slug: string) => Promise<boolean>,
  fallback = "item"
): Promise<string> {
  const base = slugify(value) || fallback;
  let candidate = base;
  let suffix = 2;

  while (await exists(candidate)) {
    candidate = `${base}-${suffix}`;
    suffix += 1;
  }

  return candidate;
}
